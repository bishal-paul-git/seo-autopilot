#!/usr/bin/env node
// Where can each job run? Follows every job module's import graph (src/jobs/*.mjs) and records what it needs from the
// runtime, then assigns an execution path. Generates docs/cloudflare/runtime-matrix.json and .md; a test keeps them in
// step with the code. Facts used (Cloudflare docs, 2026-11): node:child_process is a non-functional stub in Workers;
// node:fs is a virtual file system whose /tmp is cleared after every request; Workers Free allows 10 ms CPU and 50
// outbound requests per invocation. Measured (scripts/cf-measure.mjs): a 60-page crawl and audit costs 0.8-1.6 s CPU.
//   node scripts/cf-runtime-audit.mjs          (write)      node scripts/cf-runtime-audit.mjs --check  (exit 1 on drift)
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const rel = (p) => p.slice(root.length + 1).replace(/\\/g, "/");

function closure(entry) {
  const seen = new Set(), nodeMods = new Set(), files = [];
  const visit = (file) => {
    if (seen.has(file)) return; seen.add(file); files.push(file);
    const src = readFileSync(file, "utf8");
    for (const m of src.matchAll(/(?:^|\n)\s*(?:import|export)\s[^;]*?from\s+"([^"]+)"|import\(\s*"([^"]+)"\s*\)/g)) {
      const spec = m[1] || m[2];
      if (spec.startsWith("node:")) nodeMods.add(spec.slice(5));
      else if (spec.startsWith(".")) { try { visit(resolve(dirname(file), spec)); } catch { /* optional module */ } }
    }
  };
  visit(entry);
  const text = files.map((f) => readFileSync(f, "utf8")).join("\n");
  return {
    files: files.length, node: [...nodeMods].sort(),
    spawns: /\b(spawn|spawnSync|execFile|execFileSync|execSync)\s*\(/.test(text),
    writesFiles: /\b(writeFileSync|appendFileSync|mkdirSync|renameSync|rmSync|writeFile|appendFile)\s*\(/.test(text),
    readsFiles: /\b(readFileSync|readdirSync|existsSync|readFile)\s*\(/.test(text),
    network: /\bfetch\s*\(/.test(text), llm: /lib\/llm\.mjs|api\.anthropic\.com|chat\/completions/.test(text),
  };
}

// Hosted equivalents that exist and are tested (the job-shaped work the SEO God runs for address-only sites).
const HOSTED = {
  audit: "scan job: Supabase Edge Function `scan` (job mode, 1 site per request, <=40 pages, measured 0.8-1.6 s CPU for 60 pages vs 2 s limit), dispatched by the Worker",
  profile: "part of the scan job (site profile from the crawl)",
  priorities: "part of the scan job (priorities from the audit) and the strategy draft (Worker)",
  team: "SEO God planner (src/god/planner.mjs) in the Worker: 0.6-2.5 ms CPU per site measured",
  agent: "agent:<name> jobs in the Worker (src/god/agent-runner.mjs, advise only, user's own key): prompt build 0.6-1.1 ms CPU, the model call is I/O",
  portal: "replaced for hosted sites by Supabase rows written by the scan and the jobs",
};

function classify(name, c) {
  if (HOSTED[name]) return { path: "hosted-equivalent", where: HOSTED[name] };
  if (c.spawns) return { path: "github-actions", where: "Node host only: spawns processes (git, Go, Python or browsers); runs in the site repository's existing GitHub Actions workflows", reason: "child_process is a non-functional stub in Workers" };
  if (c.writesFiles || c.readsFiles) return { path: "github-actions", where: "Node host: reads and writes the site's state files in its repository; runs in the existing GitHub Actions workflows", reason: "Workers have no persistent file system (/tmp is cleared per request); porting needs its state moved to Supabase first" };
  return { path: "worker-candidate", where: "pure or network-only; could move to the Worker once its inputs come from Supabase", reason: "" };
}

export function audit() {
  const dir = join(root, "src/jobs");
  const jobs = readdirSync(dir).filter((f) => f.endsWith(".mjs") && f !== "index.mjs").sort().map((f) => {
    const name = f.slice(0, -4), c = closure(join(dir, f));
    return { job: name, ...classify(name, c), needs: { node: c.node, spawns: c.spawns, files: c.writesFiles ? "read-write" : c.readsFiles ? "read" : "none", network: c.network, llm: c.llm }, modules: c.files };
  });
  const count = (p) => jobs.filter((j) => j.path === p).length;
  return { jobs, summary: { total: jobs.length, hostedEquivalent: count("hosted-equivalent"), githubActions: count("github-actions"), workerCandidate: count("worker-candidate"), spawnProcesses: jobs.filter((j) => j.needs.spawns).length } };
}

function markdown(a) {
  const rows = a.jobs.map((j) => `| \`${j.job}\` | ${j.path} | ${j.needs.spawns ? "yes" : ""} | ${j.needs.files} | ${j.needs.network ? "yes" : ""} | ${j.needs.llm ? "yes" : ""} | ${j.where} |`);
  return `# Runtime matrix: where each job runs (generated)

Generated by \`node scripts/cf-runtime-audit.mjs\` from each job's import graph; \`test/cf-worker.test.mjs\` fails if it is out of date.
Decision: [D30](../implementation/DECISIONS.md). Measurements: [usage-estimate.md](usage-estimate.md).

**Summary:** ${a.summary.total} jobs.
- ${a.summary.hostedEquivalent} have a tested hosted equivalent (Worker plus the Supabase scan function).
- ${a.summary.githubActions} stay on a Node host, meaning the site repositories' existing GitHub Actions workflows.
- ${a.summary.spawnProcesses} of them spawn processes, which Workers cannot do at all.
- ${a.summary.workerCandidate} are pure or network-only candidates for a later move.

None of the CLI jobs runs inside a Worker as written. They all read or write the site's state files, and Workers have no persistent file system.

| Job | Path | Spawns | Files | Network | AI | Where it runs |
|---|---|---|---|---|---|---|
${rows.join("\n")}
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const a = audit(), out = join(root, "docs/cloudflare");
  const json = JSON.stringify(a, null, 1) + "\n", md = markdown(a);
  if (process.argv.includes("--check")) {
    const same = readFileSync(join(out, "runtime-matrix.json"), "utf8") === json && readFileSync(join(out, "runtime-matrix.md"), "utf8") === md;
    if (!same) { console.error("docs/cloudflare/runtime-matrix.* is out of date: run node scripts/cf-runtime-audit.mjs"); process.exit(1); }
    console.log("runtime matrix up to date");
  } else {
    mkdirSync(out, { recursive: true });
    writeFileSync(join(out, "runtime-matrix.json"), json); writeFileSync(join(out, "runtime-matrix.md"), md);
    console.log(JSON.stringify(a.summary));
  }
}
export { markdown };
