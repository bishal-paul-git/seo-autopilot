// Bundles the 38 agent definitions, their departments and the playbooks and skills they read (D45) into the Worker as a module, because a Worker has no access to the repository's
// files (node:fs in Workers is a per-request virtual file system). Runs before every deploy (wrangler.toml [build]).
//   node cloud/worker/build.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { listAgents } from "../../src/core/agents.mjs";
import { stripFrontMatter } from "../../src/god/agent-runner.mjs";
import { readKnowledge } from "../../src/god/knowledge.mjs";

export function prompts() {
  return Object.fromEntries(listAgents().map((a) => [a.name, stripFrontMatter(readFileSync(a.file, "utf8"))]));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const p = prompts();
  const out = fileURLToPath(new URL("./src/agents.generated.mjs", import.meta.url));
  const departments = Object.fromEntries(listAgents().map((a) => [a.name, a.department]));
  const kb = readKnowledge();
  writeFileSync(out, `// Generated by cloud/worker/build.mjs from departments/*/agents/*.md, knowledge/*.md and departments/skills. Do not edit.\nexport const PROMPTS = ${JSON.stringify(p, null, 0)};\nexport const DEPARTMENTS = ${JSON.stringify(departments)};\nexport const KNOWLEDGE = ${JSON.stringify(kb)};\n`);
  // Vertical packs for src/analysis/verticals.mjs, set before any engine module loads (imported first by worker.mjs).
  const packs = readFileSync(fileURLToPath(new URL("../../departments/verticals/packs.json", import.meta.url)), "utf8");
  writeFileSync(fileURLToPath(new URL("./src/packs.generated.mjs", import.meta.url)), `// Generated by cloud/worker/build.mjs from departments/verticals/packs.json. Do not edit.\nglobalThis.SEO_AUTOPILOT_PACKS = ${JSON.stringify(JSON.parse(packs))};\n`);
  console.log(`bundled ${Object.keys(p).length} agent definitions, ${Object.keys(kb.playbooks).length} playbooks and ${Object.keys(kb.skills).length} skills into ${out}`);
}
